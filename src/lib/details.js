function buildTimeline(stages, currentIndex, timestamps) {
  return stages.map((label, i) => ({
    label,
    time: timestamps[i] || null,
    state: i < currentIndex ? 'done' : i === currentIndex ? 'active' : 'pending',
  }))
}

